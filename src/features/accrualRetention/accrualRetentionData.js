export function formatAccrualRetentionValue(doc) {
  if (!doc) return '-'
  const ar = doc.accrual_retention_info || {}
  const type = doc.type || ar.type
  const value = doc.value ?? ar.value ?? 0
  const currency = doc.currency || ar.currency_info?.short_name || ar.currency_info?.name || 'UZS'

  if (type === 'percent') {
    return `${formatNumber(value, 2)} %`
  }
  return `${formatNumber(value, 2)} ${currency}`
}

